"""Regenerate the maintained sampling kernels from this release's vLLM source.

Use a source tree prepared by build_vllm.py, or a checkout at the pinned commit.
This developer tool is not called during inference or normal wheel packaging.
"""

from __future__ import annotations
import argparse
import ast
from copy import deepcopy
import json
from pathlib import Path
import runpy
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE_COMMIT = runpy.run_path(ROOT / "src/version.py")["load_manifest"]()["vllm"]["commit"]
OUTPUT = ROOT / "src/kernels/sampling"
INPUTS = {
    "topk": "vllm/v1/sample/ops/topk_topp_triton.py",
    "rejection": "vllm/v1/worker/gpu/spec_decode/rejection_sampler_utils.py",
}


def header(kind):
    return (
        "# SPDX-License-Identifier: Apache-2.0\n"
        "# SPDX-FileCopyrightText: Copyright contributors to the vLLM project\n"
        "# Generated by scripts/generate_sampling_kernels.py; edit the generator.\n"
        f"# Source: {INPUTS[kind]} at {SOURCE_COMMIT}\n"
        "# Changes: temperature-scaled loads and a packed selection mask; RNG and search math retained.\n"
    )


SCALE = """
@triton.jit
def _rtx_scale_logits(values, temperature):
    values = values.to(tl.float32)
    if temperature != 0.0 and temperature != 1.0:
        values = values / temperature
        # A store/reload separated this division from subsequent arithmetic
        # in the original. Keep its FP32 rounding boundary when removing it.
        values = tl.inline_asm_elementwise(
            "mov.b32 $0, $1;", constraints="=f,f", args=[values],
            dtype=tl.float32, is_pure=True, pack=1)
    return values
"""

LOAD = """
@triton.jit
def _rtx_target_load(target, row, column, target_stride,
                     filter_bits, filter_stride, mapping, temperatures,
                     mask=True, other=-float("inf")):
    req = tl.load(mapping + row)
    temperature = tl.load(temperatures + req).to(tl.float32)
    value = tl.load(target + row * target_stride + column, mask=mask, other=other)
    value = _rtx_scale_logits(value, temperature)
    word = tl.load(filter_bits + row * filter_stride + column // 32,
                   mask=mask, other=0).to(tl.uint32)
    keep = ((word >> (column % 32)) & 1) != 0
    return tl.where(keep, value, -float("inf"))
"""

FINAL = """
if not (final_pivot < max_logit):
    final_pivot = -float("inf")
for i in range(0, NUM_TILES):
    offs_n = i * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
    mask_n = offs_n < VOCAB_SIZE
    logits_blk = _rtx_scale_logits(tl.load(LOGITS_ROW + offs_n, mask=mask_n,
                             other=-float("inf")), _rtx_temp)
    keep_mask = mask_n
    if final_pivot != -float("inf"):
        keep_mask = (logits_blk > final_pivot) & mask_n
        if num_keep < num_duplicate_logit:
            duplicate_mask = (tl.abs(logits_blk - duplicate_logit) < 1e-9) & mask_n
            duplicate_count = tl.cumsum(duplicate_mask) + num_kept
            duplicate_keep_mask = (duplicate_count <= num_keep) & duplicate_mask
            duplicate_remove_mask = duplicate_mask & ~duplicate_keep_mask
            num_kept += tl.sum(duplicate_keep_mask)
            keep_mask = keep_mask & (~duplicate_remove_mask)
    bit_values = tl.reshape(keep_mask.to(tl.uint32), (BLOCK_SIZE // 32, 32))
    packed_bits = tl.sum(bit_values << tl.arange(0, 32)[None, :], axis=1)
    word_offsets = i * (BLOCK_SIZE // 32) + tl.arange(0, BLOCK_SIZE // 32)
    tl.store(_rtx_filter + row_id.to(tl.int64) * _rtx_filter_stride + word_offsets,
             packed_bits, mask=word_offsets < (VOCAB_SIZE + 31) // 32)
"""


def dotted(node):
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return dotted(node.value) + "." + node.attr
    if isinstance(node, ast.Subscript):
        return dotted(node.value)
    return ""


def extra_args(fn):
    assert not fn.args.defaults, fn.name
    for name in ("_rtx_filter", "_rtx_filter_stride", "_rtx_mapping", "_rtx_temperature"):
        fn.args.args.append(ast.arg(arg=name))


class QritaLoads(ast.NodeTransformer):
    count = 0

    def visit_Call(self, node):
        self.generic_visit(node)
        if (
            dotted(node.func) == "tl.load"
            and node.args
            and any(isinstance(n, ast.Name) and n.id == "LOGITS_ROW" for n in ast.walk(node.args[0]))
        ):
            self.count += 1
            return ast.Call(
                func=ast.Name(id="_rtx_scale_logits", ctx=ast.Load()),
                args=[node, ast.Name(id="_rtx_temp", ctx=ast.Load())],
                keywords=[],
            )
        return node


def qrita(source):
    tree = ast.parse(source)
    kernel = deepcopy(
        next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "_topk_topp_kernel")
    )
    kernel.name = "_rtx_topk_topp_mask_kernel"
    extra_args(kernel)
    loop = next(n for n in kernel.body if isinstance(n, ast.For))
    assert isinstance(loop.body[-1], ast.If) and "final_pivot < max_logit" in ast.unparse(loop.body[-1].test)
    loop.body.pop()
    assert not any(
        dotted(n.func) == "tl.store" and n.args and "LOGITS_ROW" in ast.unparse(n.args[0])
        for n in ast.walk(kernel)
        if isinstance(n, ast.Call)
    )
    visitor = QritaLoads()
    kernel = visitor.visit(kernel)
    loop = next(n for n in kernel.body if isinstance(n, ast.For))
    loop.body[0:0] = ast.parse(
        "_rtx_req = tl.load(_rtx_mapping + row_id)\n_rtx_temp = tl.load(_rtx_temperature + _rtx_req).to(tl.float32)"
    ).body
    loop.body.extend(ast.parse(FINAL).body)
    ast.fix_missing_locations(kernel)
    imports = '''"""Qrita top-k/top-p search adapted from vLLM.

Based on "Qrita: High-performance Top-k and Top-p Algorithm for GPUs using
Pivot-based Truncation and Selection" by Park et al., https://arxiv.org/abs/2602.01518.
"""
from vllm.triton_utils import tl, triton
from vllm.v1.sample.ops.topk_topp_triton import _update_min_larger_stats
'''
    return header("topk") + imports + SCALE + "\n" + ast.unparse(kernel) + "\n", {
        "original_raw_loads_scaled": visitor.count
    }


def flatten_add(node):
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return flatten_add(node.left) + flatten_add(node.right)
    return [node]


class TargetLoads(ast.NodeTransformer):
    def __init__(self):
        self.count = 0

    def visit_Call(self, node):
        self.generic_visit(node)
        if dotted(node.func) != "tl.load" or not node.args:
            return node
        terms = flatten_add(node.args[0])
        ptr = [n for n in terms if isinstance(n, ast.Name) and n.id == "target_logits_ptr"]
        if not ptr:
            return node
        products = [
            n
            for n in terms
            if isinstance(n, ast.BinOp)
            and isinstance(n.op, ast.Mult)
            and "target_logits_stride" in ast.unparse(n)
        ]
        assert len(ptr) == len(products) == 1, ast.unparse(node)
        product = products[0]
        if ast.unparse(product.left) == "target_logits_stride":
            row = product.right
        else:
            assert ast.unparse(product.right) == "target_logits_stride", ast.unparse(node)
            row = product.left
        cols = [n for n in terms if n is not ptr[0] and n is not product]
        assert len(cols) == 1, ast.unparse(node)
        self.count += 1
        return ast.Call(
            func=ast.Name(id="_rtx_target_load", ctx=ast.Load()),
            args=[
                ptr[0],
                row,
                cols[0],
                ast.Name(id="target_logits_stride", ctx=ast.Load()),
                *[
                    ast.Name(id=k, ctx=ast.Load())
                    for k in ("_rtx_filter", "_rtx_filter_stride", "_rtx_mapping", "_rtx_temperature")
                ],
            ],
            keywords=node.keywords,
        )


def rejection(source):
    tree = ast.parse(source)
    functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    changed = set()
    counts = {}
    for name, fn in functions.items():
        visitor = TargetLoads()
        visitor.visit(fn)
        if visitor.count:
            changed.add(name)
            counts[name] = visitor.count
    while True:
        old = changed.copy()
        for name, fn in functions.items():
            if any(dotted(n.func) in changed for n in ast.walk(fn) if isinstance(n, ast.Call)):
                changed.add(name)
        if old == changed:
            break
    assert "rejection_sample" in changed
    for name in changed:
        fn = functions[name]
        if name == "rejection_sample":
            fn.args.kwonlyargs.extend([ast.arg(arg="_rtx_filter"), ast.arg(arg="_rtx_filter_stride")])
            fn.args.kw_defaults.extend([ast.Constant(None), ast.Constant(0)])
        else:
            extra_args(fn)
        for node in ast.walk(fn):
            if isinstance(node, ast.Call) and dotted(node.func) in changed:
                env = (
                    ("_rtx_filter", "_rtx_filter_stride", "expanded_idx_mapping", "temperature")
                    if name == "rejection_sample"
                    else ("_rtx_filter", "_rtx_filter_stride", "_rtx_mapping", "_rtx_temperature")
                )
                node.keywords.extend(
                    ast.keyword(arg=key, value=ast.Name(id=value, ctx=ast.Load()))
                    for key, value in zip(
                        ("_rtx_filter", "_rtx_filter_stride", "_rtx_mapping", "_rtx_temperature"), env
                    )
                )
    # Helpers are inserted after imports but before original kernel definitions.
    index = next(i for i, n in enumerate(tree.body) if isinstance(n, ast.FunctionDef))
    tree.body[index:index] = ast.parse(SCALE + LOAD).body
    ast.fix_missing_locations(tree)
    return header("rejection") + ast.unparse(tree) + "\n", {
        "target_load_counts": counts,
        "transitive_functions": sorted(changed),
    }


def generate(source_dir):
    """Return deterministic source and AST admission diagnostics; import no GPU modules."""
    source_dir = Path(source_dir)
    generated, checks = {}, {}
    for kind, relative in INPUTS.items():
        source = (source_dir / relative).read_text(encoding="utf-8")
        generated[kind], checks[kind] = qrita(source) if kind == "topk" else rejection(source)
        compile(generated[kind], kind + ".py", "exec")
    return generated, checks


def validate_revision(source_dir):
    receipt = source_dir / "rtx-spark-source.json"
    if receipt.is_file():
        commit = json.loads(receipt.read_text(encoding="utf-8"))["commit"]
    else:
        commit = subprocess.check_output(
            ["git", "-C", str(source_dir), "rev-parse", "HEAD"], text=True
        ).strip()
    if commit != SOURCE_COMMIT:
        raise RuntimeError("Use this release's pinned vLLM source")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir", type=Path, required=True, help="Pinned upstream checkout or prepared vLLM source root"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=OUTPUT,
        help="Generated Python source directory (default: src/kernels/sampling)",
    )
    args = parser.parse_args()
    source = args.source_dir.resolve()
    validate_revision(source)
    generated, checks = generate(source)
    args.output.mkdir(parents=True, exist_ok=True)
    for kind, text in generated.items():
        (args.output / (kind + ".py")).write_text(text, encoding="utf-8", newline="\n")
    print(
        json.dumps(
            {
                "source_vllm_commit": SOURCE_COMMIT,
                "generated": list(generated),
                "checks": checks,
                "GPU_initialized": False,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
